/* Calculus — PWA shell.
   Reads index.json (generated by admin/pwa/deploy.py) and presents it as the
   "Binder": a rail of units and lessons, a reader that never navigates away.

   Two decisions that are load-bearing, both documented in
   admin/reference/student_site_plan.md 8:

   1. Documents are addressed by CONTENT: q/foo.html?h=<hash>.  A changed
      document is therefore a different URL, so a plain cache-first service
      worker is always correct and there is no hash bookkeeping anywhere.
   2. The four documents of the open lesson are mounted at once and toggled by
      visibility, never torn down.  Destroying an iframe reloads it, which would
      reset every slider in a Quarto's interactives.
*/
'use strict';

const CACHE_DOCS = 'calc-docs-v1';
const VIEWS = [
  { id: 'quarto',   label: 'Quarto',      hint: 'the full write-up, with the interactives' },
  { id: 'packet',   label: 'Packet',      hint: 'the questions you worked in class' },
  { id: 'ticket',   label: 'Entry ticket', hint: '' },
  { id: 'onepager', label: 'One-pager',   hint: 'the keeper' },
];
const KEYS = [
  ['/', 'Search'], ['&uarr; &darr;', 'Move between lessons'], ['&crarr;', 'Open'],
  ['Tab', 'Next document'], ['&#8984;B', 'Retract the sidebar'], ['F', 'Full screen'],
  ['G', 'Unit guide'], ['U', 'Next unit'], ['Esc', 'Back out'], ['?', 'This list'],
];

const $ = s => document.querySelector(s);
const el = (t, c, h) => { const n = document.createElement(t); if (c) n.className = c;
                          if (h != null) n.innerHTML = h; return n; };
const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;' }[c]));

const S = {                       // application state
  data: null, units: [], lessons: [], guideFor: new Map(),
  ui: 0, li: 0, view: 'quarto', mode: 'doc',
  slim: localStorage.getItem('slim') === '1',
  open: new Set(JSON.parse(localStorage.getItem('open') || '[]')),
  full: false, offline: false, cached: new Set(), hits: [], hi: 0,
  // Freshness.  The pill used to read "Up to date" whenever navigator.onLine
  // was true, which said nothing about whether the manifest was current -- an
  // app left docked and open never noticed a publish at all.
  fingerprint: '', lastCheck: 0, pending: false, checking: false,
};

/* ══════════════════════════════════════════════════════════ data ══ */

const docURL = d => d ? `${d.file}?h=${d.hash.slice(0, 12)}` : null;

/** A cheap identity for the whole manifest: every lesson's slug and every
 *  document hash.  Documents are content-addressed, so a changed hash IS a
 *  changed document -- this catches a new lesson AND a re-rendered one. */
function fingerprint(j) {
  const out = [];
  for (const u of (j.units || []))
    for (const L of (u.lessons || [])) {
      out.push(L.slug, L.quarto ? L.quarto.hash : '-');
      for (const k of Object.keys(L.docs || {}).sort()) out.push(k, L.docs[k].hash);
    }
  return out.join('|');
}

const ago = t => {
  const m = Math.floor((Date.now() - t) / 60000);
  if (m < 1)  return 'just now';
  if (m < 60) return m + ' min ago';
  const h = Math.floor(m / 60);
  return h < 24 ? h + ' h ago' : Math.floor(h / 24) + ' d ago';
};

function viewsOf(L) {
  return VIEWS.map(v => ({ ...v, doc: v.id === 'quarto' ? L.quarto : L.docs[v.id] }));
}

/** Pair each lesson with its row in the unit guide.  The guide is authoritative
 *  for Stewart sections and homework — some Quartos' <meta name="lesson"> carries
 *  the folder code rather than the textbook section. */
function linkGuide(unit) {
  for (const L of unit.lessons) {
    const code = L.code.replace(/^L/, '');
    const row = (unit.guide || []).find(r => r.kind === 'lesson' &&
      (r.name || '').replace(/\s+/g, ' ').trim().startsWith(code + ' '));
    if (row) {
      S.guideFor.set(L, row);
      L.stewart = row.stewart || L.stewart;
      L.date = row.date;
    }
  }
}

async function load() {
  let json;
  try {
    const r = await fetch('index.json', { cache: 'no-cache' });
    if (!r.ok) throw new Error(r.status);
    S.offline = r.headers.get('X-From-Cache') === '1';
    json = await r.json();
  } catch (e) {
    const c = await caches.match('index.json');
    if (!c) {
      $('#bootmsg').textContent = navigator.onLine
        ? 'Could not load the course. Try again in a moment.'
        : 'You are offline, and this device has not downloaded the course yet. Connect once and it will work offline afterwards.';
      return;
    }
    json = await c.json();
    S.offline = true;
  }
  S.data = json;
  S.fingerprint = fingerprint(json);
  S.lastCheck = Date.now();
  S.units = json.units || [];
  S.units.forEach(linkGuide);
  S.lessons = S.units.flatMap(u => u.lessons.map(L => ({ L, u })));
  if (!S.lessons.length) {
    $('#bootmsg').textContent = S.offline
      ? 'Nothing downloaded on this device yet. Reconnect once.'
      : 'No lessons published yet.';
    return;
  }

  // Default: expand the unit you were last in, or the newest one. Collapsed
  // units keep the rail short once the year has five of them.
  if (!S.open.size) S.open.add(S.units[S.units.length - 1].unit);

  const last = JSON.parse(localStorage.getItem('last') || 'null');
  if (last) {
    const i = S.lessons.findIndex(x => x.L.slug === last.slug);
    if (i >= 0) {
      S.li = i; S.ui = S.units.indexOf(S.lessons[i].u); S.view = last.view || 'quarto';
      S.open.add(S.lessons[i].u.unit);
    }
  }
  await refreshCached();
  $('#boot').remove();
  render();
}

/** Re-read the manifest and say so if it moved.  Called when the window comes
 *  back to the front and when the network returns -- load() runs once at boot,
 *  so without this a running app is frozen at whatever was published the moment
 *  it started. */
async function checkForUpdates(force) {
  if (S.checking || S.pending) return;
  if (!navigator.onLine) { S.offline = true; renderNet(); return; }
  if (!force && S.lastCheck && Date.now() - S.lastCheck < 60000) return;
  S.checking = true;
  try {
    const r = await fetch('index.json', { cache: 'no-cache' });
    if (!r.ok) throw new Error(r.status);
    // The worker served its cached copy, so this was not a real check.
    if (r.headers.get('X-From-Cache') === '1') { S.offline = true; return; }
    const j = await r.json();
    S.offline = false;
    S.lastCheck = Date.now();
    if (fingerprint(j) !== S.fingerprint) {
      S.pending = true;
      toast('New lessons are available.');
    }
  } catch (e) {
    S.offline = true;        // say the check failed rather than claim freshness
  } finally {
    S.checking = false;
    renderNet();
  }
}

async function refreshCached() {
  S.cached = new Set();
  if (!('caches' in window)) return;
  try {
    const c = await caches.open(CACHE_DOCS);
    // Key on path AND hash, exactly as the worker does.  Stripping the query
    // made a RE-RENDERED document report as saved while only its previous
    // version was cached -- the rail's dot went green and the button said
    // "Saved for offline" for a file that was not there.
    for (const req of await c.keys()) {
      const u = new URL(req.url);
      S.cached.add(ckey(u.pathname.split('/').slice(-2).join('/') + u.search));
    }
  } catch (e) { /* private mode */ }
}

/** Both key derivations run through this, because they read the same name from
 *  two places that encode it differently: cacheKey() gets the RAW string out of
 *  index.json, refreshCached() gets a URL pathname, which is percent-encoded.
 *  `q/2-1-min-max values.html` vs `q/2-1-min-max%20values.html` could never
 *  compare equal, so every Unit 2 document reported itself unsaved forever --
 *  the rail dot stayed pale and the button never flipped to "Saved for
 *  offline", while the files were in fact downloaded and available offline.
 *  deploy.py no longer publishes such a name; decoding here means a stray
 *  space, `+` or accent can never desync the two again. */
const ckey = s => { try { return decodeURIComponent(s); } catch (e) { return s; } };
const cacheKey = d => ckey(`${d.file.split('/').slice(-2).join('/')}?h=${d.hash.slice(0, 12)}`);
const isCached = d => d && S.cached.has(cacheKey(d));


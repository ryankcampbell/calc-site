function render() {
  document.body.classList.toggle('slim', S.slim);
  document.body.classList.toggle('full', S.full);
  renderRail(); renderFoot(); renderReader(); renderNet();
}

function renderRail() {
  const wide = $('#wide'), slim = $('#slim');
  wide.innerHTML = ''; slim.innerHTML = '';

  S.units.forEach((u, ui) => {
    const open = S.open.has(u.unit);
    const onGuide = S.mode === 'guide' && ui === S.ui;

    const head = el('button', 'unithead',
      `<b><span class="chev${open ? ' open' : ''}">
         <svg width="12" height="12" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.6"><path d="M9 6l6 6-6 6"/></svg>
       </span>${esc(unitTitle(u))}</b>
       <span>${open ? '' : u.lessons.length + (u.lessons.length === 1 ? ' lesson' : ' lessons')}</span>`);
    head.onclick = () => {
      S.open.has(u.unit) ? S.open.delete(u.unit) : S.open.add(u.unit);
      localStorage.setItem('open', JSON.stringify([...S.open]));
      renderRail();
    };
    wide.appendChild(head);

    // slim rail: a unit chip that also toggles, then that unit's codes
    const chip = el('button', 'uchip' + (open ? ' open' : ''), esc('U' + (u.unit.match(/\d+/) || ['?'])[0]));
    chip.onclick = head.onclick;
    tipify(chip, unitTitle(u), open ? 'click to collapse' : `${u.lessons.length} lessons — click to expand`);
    slim.appendChild(chip);

    if (!open) { slim.appendChild(el('div', 'sep')); return; }

    const g = el('button', 'lrow' + (onGuide ? ' on' : ''),
      `<span class="lcode" style="display:grid;place-items:center;padding-top:0">
         <svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7"><path d="M4 5h16v14H4z"/><path d="M4 10h16M4 15h16"/></svg>
       </span>
       <span class="lmeta"><span class="ltitle">Unit guide</span>
       <span class="lsub">every day, every problem</span></span>`);
    g.onclick = () => { S.ui = ui; S.mode = 'guide'; render(); };
    wide.appendChild(g);

    const gi = el('button', 'srow' + (onGuide ? ' on' : ''),
      `<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8"><path d="M4 5h16v14H4z"/><path d="M4 10h16M4 15h16"/></svg>`);
    gi.onclick = g.onclick;
    tipify(gi, 'Unit guide', unitTitle(u));
    slim.appendChild(gi);
    slim.appendChild(el('div', 'sep'));

    (u.guide && u.guide.length ? u.guide : u.lessons.map(L => ({ kind: 'lesson', _L: L })))
      .forEach(row => railRow(u, row, wide, slim));
    slim.appendChild(el('div', 'sep'));
  });
}

function railRow(u, row, wide, slim) {
  if (row.kind === 'break') {
    wide.appendChild(el('div', 'brk', esc(row.text || '')));
    slim.appendChild(el('div', 'sep'));
    return;
  }
  if (row.kind === 'banner') return;

  if (row.kind !== 'lesson') {                       // quiz / review / exam
    const exam = row.kind === 'exam';
    wide.appendChild(el('div', 'assess' + (exam ? ' exam' : ''),
      `<span>${esc(row.name)}</span><span style="opacity:.6;font-weight:400">${esc(row.date || '')}</span>`));
    const b = el('div', 'srow', `<span class="sbar${exam ? ' exam' : ''}"></span>`);
    tipify(b, row.name, row.date || '');
    slim.appendChild(b);
    return;
  }

  const L = row._L || S.lessons.find(x => x.u === u && S.guideFor.get(x.L) === row)?.L;
  if (!L) {                                          // scheduled, not published yet
    wide.appendChild(el('div', 'assess',
      `<span style="color:var(--ink-4);font-weight:400">${esc(row.name)}</span>
       <span style="opacity:.5;font-weight:400">${esc(row.date || '')}</span>`));
    slim.appendChild(el('div', 'srow', `<span class="sbar" style="background:#eef2f6"></span>`));
    return;
  }

  const i = S.lessons.findIndex(x => x.L === L);
  const on = S.mode === 'doc' && i === S.li;
  const ok = isCached(L.quarto);
  const r = el('button', 'lrow' + (on ? ' on' : ''),
    `<span class="lcode">${esc(L.code)}</span>
     <span class="lmeta"><span class="ltitle">${esc(L.title)}</span>
     <span class="lsub">${esc(L.stewart ? '§' + L.stewart.replace(/^§/, '') : '')}</span></span>
     <span class="dot ${ok ? '' : 'pale'}" style="margin-top:5px"></span>`);
  r.onclick = () => pick(i);
  wide.appendChild(r);

  const s = el('button', 'srow' + (on ? ' on' : ''),
    `<span class="scode">${esc(L.code.replace(/^L/, ''))}</span><span class="dot ${ok ? '' : 'pale'}"></span>`);
  s.onclick = () => pick(i);
  tipify(s, L.title, `${L.code}${L.stewart ? ' · §' + L.stewart.replace(/^§/, '') : ''}`);
  slim.appendChild(s);
}

/** "unit1-review" -> "Unit 1 · Review",
 *  "unit2-applications_of_derivatives" -> "Unit 2 · Applications of Derivatives".
 *  The guide's banner is the subtitle, not the title — it is a full sentence and
 *  reads as shouting in the rail.
 *
 *  Separators have to be turned into spaces BEFORE title-casing: `_` is a word
 *  character, so \b never fires after one and the old version shipped
 *  "Applications_of_derivatives" straight into the rail. */
const UNIT_SMALL = new Set(['of', 'the', 'and', 'a', 'an', 'to', 'in', 'for', 'at', 'by', 'from', 'on', 'vs']);
const unitCase = s => s.split(/\s+/).filter(Boolean)
  .map((w, i) => (i && UNIT_SMALL.has(w.toLowerCase()))
    ? w.toLowerCase()
    : w.charAt(0).toUpperCase() + w.slice(1))
  .join(' ');
const unitTitle = u => u.unit.replace(/^unit(\d+)-?/, 'Unit $1 · ')
  .split('·').map(s => unitCase(s.trim().replace(/[_-]+/g, ' '))).join(' · ');
const unitSub = u => ((u.guide || []).find(r => r.kind === 'banner')?.text || '')
  .replace(/^REVIEW:\s*/i, '').trim();

/** The rail scrolls, so an absolutely-positioned tooltip inside it is clipped
 *  by overflow-x.  One shared fixed element, positioned on hover, instead. */
function tipify(node, title, sub) {
  node.onmouseenter = () => {
    if (!S.slim) return;
    const t = $('#tip'), r = node.getBoundingClientRect();
    t.innerHTML = `<b>${esc(title)}</b><span>${esc(sub)}</span>`;
    t.style.display = 'block';
    t.style.left = (r.right + 10) + 'px';
    t.style.top = Math.max(8, r.top + r.height / 2 - t.offsetHeight / 2) + 'px';
  };
  node.onmouseleave = () => { $('#tip').style.display = 'none'; };
}

function renderFoot() {
  const u = S.units[S.ui];
  const files = u.lessons.flatMap(L => [L.quarto, ...Object.values(L.docs)]);
  // Only what is actually missing.  Documents are content-addressed, so an
  // unchanged file is already a cache hit and costs nothing -- quoting the
  // whole unit's size after a one-lesson publish read as "re-download 45 MB",
  // which is not what happens.
  const missing = files.filter(f => !isCached(f));
  S.savedAll = missing.length === 0;
  const mb = missing.reduce((a, f) => a + f.bytes, 0) / 1e6;
  const size = mb < 1 ? mb.toFixed(1) : mb.toFixed(0);
  const partial = missing.length > 0 && missing.length < files.length;
  const b = $('#savebtn');
  b.innerHTML = S.savedAll
    ? `<svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M20 6L9 17l-5-5"/></svg> Saved for offline`
    : `<svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M12 3v12m0 0l-4-4m4 4l4-4M4 19h16"/></svg> ${partial ? 'Save what&rsquo;s new' : 'Save this unit'} <small>${size} MB</small>`;
  b.disabled = S.savedAll;
  b.onclick = () => saveUnit(u, missing);
}

async function saveUnit(u, files) {
  const b = $('#savebtn');
  b.disabled = true;
  let done = 0;
  for (const f of files) {
    try { await fetch(docURL(f)); } catch (e) { /* keep going */ }
    done++;
    b.innerHTML = `Saving&hellip; <small>${done} of ${files.length}</small>`;
  }
  await refreshCached();
  render();
}

